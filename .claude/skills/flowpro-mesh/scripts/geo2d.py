"""Builder of MeshGenerator2D geometries (.geo2d) for FlowPro.

Usage as a module (copy next to your script or add this directory to sys.path):

    from geo2d import Geometry, rectangle, circle, naca4
    g = Geometry(mesh_size=0.5, min_angle=28, grading=0.25)
    g.loop(rectangle(-10, -10, 30, 10, types=(-4, -3, -4, -2), ale=1))   # outer boundary first
    g.loop(circle(0, 0, 0.5, n=120, type=-1, h=0.03, ale=2))             # body (hole)
    g.region_box(-1, -1.5, 15, 1.5, 0.12)                                # wake refinement
    g.save("simulations/NAME/mesh/geometry.geo2d")

Then mesh it:
    java -jar MeshGenerator2D.jar --batch simulations/NAME/mesh/geometry.geo2d simulations/NAME/mesh

A loop is a list of (x, y, type, h, ale) tuples; the attributes belong to the segment from this
point to the next one. type = FlowPro boundary type (-1 wall, -2 inlet, -3 outlet, -4 inviscid wall,
-5 free inlet/outlet of the compressible models), h = local cell size (nan = global), ale = ALE tag
(0 none, 1 fixed boundary, 2 body 1, 3 body 2, ...).
"""
import math

NAN = float("nan")


def _fmt(v):
    return "NaN" if v != v else repr(float(v))


class Geometry:
    def __init__(self, mesh_size=0.1, min_angle=28, grading=0.3, smoothing=5, refinement=0, block_triangles=False):
        self.params = dict(meshSize=mesh_size, minAngle=min_angle, grading=grading,
                           smoothing=int(smoothing), refinement=int(refinement),
                           blockTriangles=1 if block_triangles else 0)
        self.loops = []
        self.regions = []
        self.vertices = []
        self.blocks = []
        self.arcs = []

    # ------------------------------------------------------------ unstructured part
    def loop(self, points):
        """closed loop; the loop with the largest area is the outer boundary, the others are holes"""
        self.loops.append(list(points))
        return self

    def region_box(self, x0, y0, x1, y1, h):
        """the cell size is at most h inside the box and grows with 'grading' outside"""
        self.regions.append(f"region box {x0} {y0} {x1} {y1} {h}")
        return self

    def region_circle(self, cx, cy, r, h):
        self.regions.append(f"region circle {cx} {cy} {r} {h}")
        return self

    # ------------------------------------------------------------ structured blocks
    def vertex(self, x, y):
        """block vertex, returns its index"""
        self.vertices.append((x, y))
        return len(self.vertices) - 1

    def block(self, v, nx, ny, gx=1.0, gy=1.0, types=(-1, -1, -1, -1), ale=(0, 0, 0, 0)):
        """quadrilateral block, vertices v0..v3 counter-clockwise; face k goes from v[k] to v[k+1].
        faces 0, 2 have nx cells, faces 1, 3 ny cells; gx = last/first cell along v0->v1,
        gy along v1->v2; types/ale are used only for faces not shared with another block"""
        vals = list(v) + [nx, ny, gx, gy] + list(types) + list(ale)
        self.blocks.append("block " + " ".join(str(x) for x in vals))
        return self

    def arc(self, a, b, x, y):
        """the block edge between vertices a and b is a circular arc through (x, y)"""
        self.arcs.append(f"arc {a} {b} {x} {y}")
        return self

    # ------------------------------------------------------------ output
    def save(self, path):
        with open(path, "w") as f:
            f.write("# FlowPro 2D geometry (generated by geo2d.py)\n")
            for k, v in self.params.items():
                f.write(f"{k} {v}\n")
            for r in self.regions:
                f.write(r + "\n")
            for x, y in self.vertices:
                f.write(f"vertex {x!r} {y!r}\n")
            for b in self.blocks:
                f.write(b + "\n")
            for a in self.arcs:
                f.write(a + "\n")
            for lp in self.loops:
                f.write("loop\n")
                for x, y, t, h, ale in lp:
                    f.write(f"point {x!r} {y!r} {int(t)} {_fmt(h)} {int(ale)}\n")
                f.write("end\n")


# ---------------------------------------------------------------- loop helpers
def polyline(points, type=-1, h=NAN, ale=0):
    """loop from a list of (x, y); all segments get the same attributes"""
    return [(x, y, type, h, ale) for x, y in points]


def rectangle(x0, y0, x1, y1, types=(-1, -1, -1, -1), h=NAN, ale=0, n=(1, 1, 1, 1)):
    """counter-clockwise rectangle; types/n for the sides bottom, right, top, left;
    n = number of segments per side (only geometric points, the mesh size is given by h/meshSize)"""
    corners = [(x0, y0), (x1, y0), (x1, y1), (x0, y1)]
    hs = h if isinstance(h, (tuple, list)) else (h,) * 4
    ales = ale if isinstance(ale, (tuple, list)) else (ale,) * 4
    pts = []
    for s in range(4):
        (xa, ya), (xb, yb) = corners[s], corners[(s + 1) % 4]
        for i in range(n[s]):
            u = i / n[s]
            pts.append((xa + u * (xb - xa), ya + u * (yb - ya), types[s], hs[s], ales[s]))
    return pts


def circle(cx, cy, r, n=64, type=-1, h=NAN, ale=0, types=None):
    """circle with n points (counter-clockwise); types(phi) may give the type of each segment
    by the angle of its midpoint, e.g. far field: lambda phi: -3 if math.cos(phi) > 0 else -2"""
    pts = []
    for i in range(n):
        phi = 2 * math.pi * i / n
        t = types(2 * math.pi * (i + 0.5) / n) if types else type
        pts.append((cx + r * math.cos(phi), cy + r * math.sin(phi), t, h, ale))
    return pts


def naca4(code="0012", n=80, chord=1.0, x0=0.0, y0=0.0, alpha_deg=0.0, type=-1, h=NAN, ale=0):
    """NACA 4-digit airfoil with a closed trailing edge (cosine spacing, n points per side),
    leading edge at (x0, y0), rotated by alpha (positive = nose up, i.e. clockwise)"""
    m, p, t = int(code[0]) / 100, int(code[1]) / 10, int(code[2:]) / 100
    raw = []
    for side in (0, 1):  # lower TE -> LE, upper LE -> TE
        for i in range(n):
            k = n - i if side == 0 else i
            if side == 1 and i == 0:
                continue
            x = 0.5 * (1 - math.cos(math.pi * k / n))
            yt = 5 * t * (0.2969 * math.sqrt(x) - 0.1260 * x - 0.3516 * x**2 + 0.2843 * x**3 - 0.1036 * x**4)
            if m > 0 and p > 0:
                yc = m / p**2 * (2 * p * x - x * x) if x < p else m / (1 - p) ** 2 * (1 - 2 * p + 2 * p * x - x * x)
                dyc = 2 * m / p**2 * (p - x) if x < p else 2 * m / (1 - p) ** 2 * (p - x)
            else:
                yc = dyc = 0.0
            th = math.atan(dyc)
            sgn = -1 if side == 0 else 1
            raw.append((x - sgn * yt * math.sin(th), yc + sgn * yt * math.cos(th)))
    a = -math.radians(alpha_deg)
    pts = []
    for x, y in raw:  # the trailing edge point is only once (closed loop)
        xr, yr = x * math.cos(a) - y * math.sin(a), x * math.sin(a) + y * math.cos(a)
        pts.append((x0 + chord * xr, y0 + chord * yr, type, h, ale))
    return pts
